-- 建立檢查密碼的 RPC
CREATE OR REPLACE FUNCTION verify_admin_password(p_password text, p_user_agent text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  is_valid boolean;
  client_ip text;
BEGIN
  SELECT EXISTS(SELECT 1 FROM public.admin_users WHERE password = p_password) INTO is_valid;
  
  BEGIN
    client_ip := current_setting('request.headers', true)::json->>'x-forwarded-for';
  EXCEPTION WHEN OTHERS THEN
    client_ip := 'unknown';
  END;

  INSERT INTO public.admin_logs (status, ip_address, user_agent) 
  VALUES (CASE WHEN is_valid THEN 'SUCCESS' ELSE 'FAILED' END, client_ip, p_user_agent);
  
  RETURN is_valid;
END;
$$;

-- 提供修改密碼的 RPC
CREATE OR REPLACE FUNCTION update_admin_password(old_password text, new_password text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  is_valid boolean;
BEGIN
  SELECT EXISTS(SELECT 1 FROM public.admin_users WHERE password = old_password) INTO is_valid;
  IF is_valid THEN
    UPDATE public.admin_users SET password = new_password WHERE password = old_password;
    RETURN true;
  END IF;
  RETURN false;
END;
$$;


